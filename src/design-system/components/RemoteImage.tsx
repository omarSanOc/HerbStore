import { Image, type ImageContentFit } from 'expo-image';
import { useState } from 'react';
import { StyleSheet, View, type StyleProp, type ViewStyle } from 'react-native';

import { useReducedMotionPreference } from '@/core/accessibility/use-reduced-motion';
import { apiOrigin } from '@/core/network/api-origin';
import { resolveAssetUrl } from '@/core/network/resolve-asset-url';
import { AppText } from '@/design-system/components/AppText';
import { spacing } from '@/design-system/tokens';
import { useAppTheme } from '@/design-system/theme';

/** Cross-fade when the image arrives; 0 with reduced motion (no non-essential transitions). */
const FADE_IN_MS = 200;

type RemoteImageProps = {
  /** Server path such as `/images/products/x.png`; it is resolved against the API origin. */
  path: string | undefined;
  /**
   * Width / height of the reserved frame. The frame has this shape BEFORE the image loads, so the
   * layout never jumps. Give the frame a width (or let the parent define it) through `style`.
   */
  aspectRatio: number;
  /**
   * What a screen reader says. Pass it when the image carries information on its own; omit it
   * when it is decorative because the parent already describes it (a card, a category button),
   * and the image then disappears from the accessibility tree instead of adding noise.
   */
  label?: string;
  /** Visible text when the image cannot be shown (missing path, 404, network). Localized. */
  fallbackText: string;
  /** `cover` fills the frame; the mock serves images with the frame's exact proportions. */
  contentFit?: ImageContentFit;
  style?: StyleProp<ViewStyle>;
};

/**
 * A remote image with a reserved frame, a placeholder and a labelled fallback, on `expo-image`
 * (native disk and memory cache, off-thread decoding; React Native's `Image` caches far less).
 *
 * - Placeholder: the frame paints a neutral color until the bitmap arrives. A blurhash would need
 *   a hash per image generated by the server, which the flat generated images do not justify.
 * - Failure: `onError` (or an unusable path) swaps the image for visible text. Failure is stored as
 *   "the URI that failed", so a different URI (the server changed it) tries again without an effect.
 * - `recyclingKey` is the resolved URI. React Native's `FlatList` does not reuse component
 *   instances, so today it changes nothing; it is what keeps a recycled view from flashing the
 *   previous bitmap once lists move to FlashList (Day 3), and it costs nothing now.
 */
export function RemoteImage({
  path,
  aspectRatio,
  label,
  fallbackText,
  contentFit = 'cover',
  style,
}: Readonly<RemoteImageProps>) {
  const { colors } = useAppTheme();
  const reduceMotion = useReducedMotionPreference();
  const uri = resolveAssetUrl(apiOrigin, path);
  const [failedUri, setFailedUri] = useState<string | undefined>(undefined);
  const failed = uri === undefined || failedUri === uri;
  const isLabelled = label !== undefined;

  return (
    <View
      accessibilityElementsHidden={!isLabelled}
      accessibilityLabel={isLabelled ? (failed ? `${label}. ${fallbackText}` : label) : undefined}
      accessibilityRole={isLabelled ? 'image' : undefined}
      accessible={isLabelled}
      importantForAccessibility={isLabelled ? 'yes' : 'no-hide-descendants'}
      style={[styles.frame, { aspectRatio, backgroundColor: colors.border }, style]}>
      {failed ? (
        <View style={styles.fallback}>
          <AppText style={styles.fallbackText} tone="muted">
            {fallbackText}
          </AppText>
        </View>
      ) : (
        <Image
          accessible={false}
          contentFit={contentFit}
          onError={() => {
            if (__DEV__) {
              console.log(`[image] could not load ${path ?? 'an empty path'}`);
            }
            setFailedUri(uri);
          }}
          recyclingKey={uri}
          source={{ uri }}
          style={StyleSheet.absoluteFill}
          transition={reduceMotion ? 0 : FADE_IN_MS}
        />
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  frame: {
    overflow: 'hidden',
  },
  fallback: {
    position: 'absolute',
    top: 0,
    right: 0,
    bottom: 0,
    left: 0,
    alignItems: 'center',
    justifyContent: 'center',
    padding: spacing.xs,
  },
  fallbackText: {
    // Small on purpose: this text lives inside a frame whose size does not grow with the font.
    fontSize: 13,
    lineHeight: 16,
    textAlign: 'center',
  },
});
